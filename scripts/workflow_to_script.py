def main():
    parser = argparse.ArgumentParser(description="Generate executable Python agent skeletons from Markdown workflows.")
    parser.add_argument("workflow_file", help="Path to the workflow markdown file (e.g. .agents/workflows/reposcout_agent.md)")
    parser.add_argument("-o", "--output", help="Optional path to output script. If not set, saves to scripts/agent_<name>.py")
    args = parser.parse_args()

    try:
        metadata = parse_markdown_workflow(args.workflow_file)
        script_content = generate_python_script(metadata)
        
        if args.output:
            out_path = args.output
        else:
            filename = metadata["agent_name"].lower().replace(" ", "_") + ".py"
            out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), filename)

        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(script_content)

        # Make executable
        os.chmod(out_path, 0o755)
        print(f"[+] Successfully generated executable agent script at: {out_path}")
        
    except Exception as e:
        print(f"[!] Error: {e}", file=sys.stderr)
        sys.exit(1)

if __name__ == "__main__":
    main()
