def parse_markdown_workflow(file_path):
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Workflow file not found at: {file_path}")

    with open(file_path, "r", encoding="utf-8") as f:
        raw_content = f.read()

    # Split frontmatter
    yaml_metadata = {}
    content = raw_content
    if raw_content.startswith("---"):
        parts = raw_content.split("---", 2)
        if len(parts) >= 3:
            try:
                yaml_metadata = yaml.safe_load(parts[1]) or {}
            except Exception as e:
                print(f"[!] Error parsing YAML frontmatter: {e}", file=sys.stderr)
            content = parts[2]

    # Find Agent Title (First # heading)
    title_match = re.search(r"^#\s+(.*)", content, re.MULTILINE)
    agent_name = title_match.group(1).strip() if title_match else "Autogen Agent"

    # Extract sections using regex
    sections = {}
    current_section = None
    section_content = []

    for line in content.split("\n"):
        header_match = re.match(r"^##\s+(.*)", line)
        if header_match:
            if current_section:
                sections[current_section] = "\n".join(section_content).strip()
            current_section = header_match.group(1).strip().lower()
            section_content = []
        else:
            section_content.append(line)

    if current_section:
        sections[current_section] = "\n".join(section_content).strip()

    # Parse Inputs
    inputs = []
    inputs_text = sections.get("inputs", "")
    # Find list items: - `name` (type): description. Default: val
    input_items = re.findall(r"^-\s+`([^`]+)`\s+\(([^)]+)\):\s*(.*?)(?:\.\s*Default:\s*(.*))?$", inputs_text, re.MULTILINE)
    
    for item in input_items:
        name = item[0].strip()
        var_type = item[1].strip().lower()
        desc = item[2].strip()
        default_val = item[3].strip() if len(item) > 3 else "None"
        
        # Parse default value
        if default_val.lower() == "null" or default_val == "":
            default_val = "None"
        elif var_type == "boolean":
            default_val = "True" if default_val.lower() in ("true", "yes", "1") else "False"
        elif var_type == "integer":
            try:
                default_val = str(int(default_val))
            except ValueError:
                default_val = "None"
        elif var_type == "array":
            # Strip brackets and split by comma if list
            clean_val = re.sub(r"[\[\]'\"]", "", default_val)
            if clean_val.lower() == "none" or clean_val.lower() == "null" or not clean_val:
                default_val = "[]"
            else:
                items = [x.strip() for x in clean_val.split(",")]
                default_val = str(items)
        
        inputs.append({
            "name": name,
            "type": var_type,
            "description": desc,
            "default": default_val
        })

    # Parse Output JSON
    output_json_block = ""
    output_json_text = sections.get("output json", "")
    json_match = re.search(r"```json\s*(.*?)\s*```", output_json_text, re.DOTALL)
    if json_match:
        output_json_block = json_match.group(1).strip()
    else:
        # Try finding standard JSON inside the block
        json_match_fallback = re.search(r"({.*})", output_json_text, re.DOTALL)
        if json_match_fallback:
            output_json_block = json_match_fallback.group(1).strip()

    # Parse Rules
    rules = []
    rules_text = sections.get("rules", "")
    rule_items = re.findall(r"^-\s+(.*)$", rules_text, re.MULTILINE)
    for rule in rule_items:
        rules.append(rule.strip())

    # Parse Failure Codes
    failure_codes = []
    failure_codes_text = sections.get("failure codes", "")
    # Match - **CODE**: Description
    code_items = re.findall(r"^-\s+\*\*([^*]+)\*\*:\s*(.*)$", failure_codes_text, re.MULTILINE)
    for code, desc in code_items:
        failure_codes.append({
            "code": code.strip(),
            "description": desc.strip()
        })

    return {
        "agent_name": agent_name,
        "description": yaml_metadata.get("description", "Autogenerated agent script from workflow."),
        "inputs": inputs,
        "output_json_template": output_json_block,
        "rules": rules,
        "failure_codes": failure_codes
    }

